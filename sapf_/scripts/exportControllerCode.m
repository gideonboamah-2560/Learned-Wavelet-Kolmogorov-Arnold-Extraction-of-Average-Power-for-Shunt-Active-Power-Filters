% exportControllerCode.m
% Reads results/trainedControllers.mat and writes four SELF-CONTAINED
% controller files, each implementing the full reference-current
% generator (Clarke transform -> extraction filter -> DC-link PI ->
% inverse Clarke) as a single function with the trained weights baked in
% as numeric literals. Each file is meant to be pasted directly into a
% Simulink "MATLAB Function" block (persistent variables give it state
% across simulation steps, exactly as MATLAB Function blocks require).
%
% Run this once, after trainControllers.m, from the scripts/ folder.

clear; clc;
here = fileparts(mfilename('fullpath'));
addpath(fullfile(here, '../models'));
outDir = fullfile(here, '../simulink');
if ~exist(outDir, 'dir'), mkdir(outDir); end

S = load(fullfile(here, '../results/trainedControllers.mat'));

%% ---- 1) Analytic p-q theory + PI (no trained weights, just biquad coeffs)
fid = fopen(fullfile(outDir, 'ctrl_pq_pi.m'), 'w');
fprintf(fid, '%s', genHeader('ctrl_pq_pi', ...
    'Classical p-q theory reference-current generator (2nd-order Butterworth LPF extraction).'));
fprintf(fid, [ ...
"persistent w1 w2 dcInt initialized\n" ...
"b = %s; a = %s;\n" ...
"if isempty(initialized)\n" ...
"    w1 = 0; w2 = 0; dcInt = 0; initialized = true;\n" ...
"end\n\n" ...
"[vAlpha, vBeta, iAlpha, iBeta, p, q] = clarkeAndPower(vA,vB,vC,iLA,iLB,iLC);\n\n" ...
"%% Direct-Form-II biquad low-pass on p -> pbar\n" ...
"y = b(1)*p + w1;\n" ...
"w1 = b(2)*p - a(2)*y + w2;\n" ...
"w2 = b(3)*p - a(3)*y;\n" ...
"pbar = y;\n\n" ...
"[icRefA, icRefB, icRefC, dcInt] = dcRegAndInvClarke(p, q, pbar, Vdc, VdcRef, Ts, dcInt, vAlpha, vBeta);\n" ...
"end\n\n"], mat2strf(S.lpf_b), mat2strf(S.lpf_a));
fprintf(fid, '%s', sharedSubfunctions());
fclose(fid);

%% ---- 2) Fixed-wavelet WNN
K = numel(S.wnnFixed.a); N = size(S.wnnP.v,1);
fid = fopen(fullfile(outDir, 'ctrl_fixed_wnn.m'), 'w');
fprintf(fid, '%s', genHeader('ctrl_fixed_wnn', ...
    'Fixed-dilation/translation wavelet neural network (Zhang-Benveniste wavelon) reference-current generator.'));
fprintf(fid, [ ...
"persistent buf dcInt initialized\n" ...
"persistent v w w0 aFix bFix\n" ...
"N = %d;\n" ...
"if isempty(initialized)\n" ...
"    buf = zeros(1,N); dcInt = 0;\n" ...
"    v = %s;\n" ...
"    w = %s;\n" ...
"    w0 = %.8g;\n" ...
"    aFix = %s;\n" ...
"    bFix = %s;\n" ...
"    initialized = true;\n" ...
"end\n\n" ...
"[vAlpha, vBeta, iAlpha, iBeta, p, q] = clarkeAndPower(vA,vB,vC,iLA,iLB,iLC);\n" ...
"buf = [buf(2:end), p];\n" ...
"pbar = wnnForwardEmbedded(buf, v, w, w0, aFix, bFix);\n\n" ...
"[icRefA, icRefB, icRefC, dcInt] = dcRegAndInvClarke(p, q, pbar, Vdc, VdcRef, Ts, dcInt, vAlpha, vBeta);\n" ...
"end\n\n" ...
"function y = wnnForwardEmbedded(x, v, w, w0, aFix, bFix)\n" ...
"scale = mean(abs(x)) + 1.0;\n" ...
"xn = x / scale;\n" ...
"z = xn * v;                    %% (1 x K)\n" ...
"u = (z - bFix) ./ aFix;\n" ...
"h = (1 - u.^2) .* exp(-0.5*u.^2);\n" ...
"yN = h*w + w0;\n" ...
"y = yN * scale;\n" ...
"end\n\n" ], N, mat2strf(S.wnnP.v), mat2strf(S.wnnP.w), S.wnnP.w0, mat2strf(S.wnnFixed.a), mat2strf(S.wnnFixed.b));
fprintf(fid, '%s', sharedSubfunctions());
fclose(fid);

%% ---- 3) GRU-lite
H = S.gruH;
fid = fopen(fullfile(outDir, 'ctrl_gru.m'), 'w');
fprintf(fid, '%s', genHeader('ctrl_gru', ...
    'Small GRU (gated recurrent unit) reference-current generator (2025-style deep-learning baseline).'));
fprintf(fid, [ ...
"persistent buf dcInt initialized\n" ...
"persistent Wr Ur br Wz Uz bz Wn Un bn Wo bo\n" ...
"N = 32; H = %d;\n" ...
"if isempty(initialized)\n" ...
"    buf = zeros(1,N); dcInt = 0;\n" ...
"    Wr=%s; Ur=%s; br=%s;\n" ...
"    Wz=%s; Uz=%s; bz=%s;\n" ...
"    Wn=%s; Un=%s; bn=%s;\n" ...
"    Wo=%s; bo=%.8g;\n" ...
"    initialized = true;\n" ...
"end\n\n" ...
"[vAlpha, vBeta, iAlpha, iBeta, p, q] = clarkeAndPower(vA,vB,vC,iLA,iLB,iLC);\n" ...
"buf = [buf(2:end), p];\n" ...
"pbar = gruForwardEmbedded(buf, H, Wr,Ur,br,Wz,Uz,bz,Wn,Un,bn,Wo,bo);\n\n" ...
"[icRefA, icRefB, icRefC, dcInt] = dcRegAndInvClarke(p, q, pbar, Vdc, VdcRef, Ts, dcInt, vAlpha, vBeta);\n" ...
"end\n\n" ...
"function y = gruForwardEmbedded(x, H, Wr,Ur,br,Wz,Uz,bz,Wn,Un,bn,Wo,bo)\n" ...
"scale = mean(abs(x)) + 1.0;\n" ...
"xn = x / scale;\n" ...
"h = zeros(1,H);\n" ...
"N = numel(xn);\n" ...
"for t = 1:N\n" ...
"    xt = xn(t);\n" ...
"    r = 1./(1+exp(-(xt*Wr + h*Ur + br)));\n" ...
"    z = 1./(1+exp(-(xt*Wz + h*Uz + bz)));\n" ...
"    Un_h = h*Un;\n" ...
"    npre = xt*Wn + r.*Un_h + bn;\n" ...
"    n = tanh(npre);\n" ...
"    h = (1-z).*n + z.*h;\n" ...
"end\n" ...
"yN = h*Wo + bo;\n" ...
"y = yN * scale;\n" ...
"end\n\n" ], H, mat2strf(S.gruP.Wr), mat2strf(S.gruP.Ur), mat2strf(S.gruP.br), ...
      mat2strf(S.gruP.Wz), mat2strf(S.gruP.Uz), mat2strf(S.gruP.bz), ...
      mat2strf(S.gruP.Wn), mat2strf(S.gruP.Un), mat2strf(S.gruP.bn), ...
      mat2strf(S.gruP.Wo), S.gruP.bo);
fprintf(fid, '%s', sharedSubfunctions());
fclose(fid);

%% ---- 4) Wav-KAN (proposed)
fid = fopen(fullfile(outDir, 'ctrl_wavkan.m'), 'w');
fprintf(fid, '%s', genHeader('ctrl_wavkan', ...
    'PROPOSED: Wavelet Kolmogorov-Arnold Network reference-current generator. Every edge (input->hidden, hidden->output) is its own learnable wavelet with trained scale/translation/amplitude.'));
fprintf(fid, [ ...
"persistent buf dcInt initialized\n" ...
"persistent a1 b1 c1 a2 b2 c2 biasK\n" ...
"N = 32;\n" ...
"if isempty(initialized)\n" ...
"    buf = zeros(1,N); dcInt = 0;\n" ...
"    a1 = %s; b1 = %s; c1 = %s;\n" ...
"    a2 = %s; b2 = %s; c2 = %s;\n" ...
"    biasK = %.8g;\n" ...
"    initialized = true;\n" ...
"end\n\n" ...
"[vAlpha, vBeta, iAlpha, iBeta, p, q] = clarkeAndPower(vA,vB,vC,iLA,iLB,iLC);\n" ...
"buf = [buf(2:end), p];\n" ...
"pbar = wavkanForwardEmbedded(buf, a1,b1,c1,a2,b2,c2,biasK);\n\n" ...
"[icRefA, icRefB, icRefC, dcInt] = dcRegAndInvClarke(p, q, pbar, Vdc, VdcRef, Ts, dcInt, vAlpha, vBeta);\n" ...
"end\n\n" ...
"function y = wavkanForwardEmbedded(x, a1,b1,c1,a2,b2,c2,biasK)\n" ...
"scale = mean(abs(x)) + 1.0;\n" ...
"xn = x / scale;\n" ...
"nHidden = size(a1,2);\n" ...
"h = zeros(1,nHidden);\n" ...
"for k = 1:nHidden\n" ...
"    u = (xn - b1(:,k)') ./ a1(:,k)';\n" ...
"    psi = (1 - u.^2) .* exp(-0.5*u.^2);\n" ...
"    h(k) = sum(c1(:,k)' .* psi);\n" ...
"end\n" ...
"v = (h - b2') ./ a2';\n" ...
"psiv = (1 - v.^2) .* exp(-0.5*v.^2);\n" ...
"yN = sum(c2' .* psiv) + biasK;\n" ...
"y = yN * scale;\n" ...
"end\n\n" ], mat2strf(S.wkP.a1), mat2strf(S.wkP.b1), mat2strf(S.wkP.c1), ...
      mat2strf(S.wkP.a2), mat2strf(S.wkP.b2), mat2strf(S.wkP.c2), S.wkP.bias);
fprintf(fid, '%s', sharedSubfunctions());
fclose(fid);

fprintf('Wrote 4 Simulink-ready controller files to %s\n', outDir);
