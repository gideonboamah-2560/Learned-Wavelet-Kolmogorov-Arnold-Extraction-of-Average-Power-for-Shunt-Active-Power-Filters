function s = sharedSubfunctions()
s = sprintf([ ...
"function [vAlpha,vBeta,iAlpha,iBeta,p,q] = clarkeAndPower(vA,vB,vC,iLA,iLB,iLC)\n" ...
"vAlpha = (2/3)*(vA - 0.5*vB - 0.5*vC);\n" ...
"vBeta  = (2/3)*(sqrt(3)/2)*(vB - vC);\n" ...
"iAlpha = (2/3)*(iLA - 0.5*iLB - 0.5*iLC);\n" ...
"iBeta  = (2/3)*(sqrt(3)/2)*(iLB - iLC);\n" ...
"p = vAlpha*iAlpha + vBeta*iBeta;\n" ...
"q = vAlpha*iBeta  - vBeta*iAlpha;\n" ...
"end\n\n" ...
"function [icRefA,icRefB,icRefC,dcInt] = dcRegAndInvClarke(p,q,pbar,Vdc,VdcRef,Ts,dcInt,vAlpha,vBeta)\n" ...
"%% DC-link voltage regulation (adds active power reference to recharge/\n" ...
"%% discharge the capacitor) + full reactive-power compensation (qc = q).\n" ...
"%% Tuned for wn=2*pi*8 rad/s, zeta=0.7 with C=2000uF, Vref=800V:\n" ...
"%%   Kp = 2*zeta*wn*C*Vref, Ki = wn^2*C*Vref  (units: W/V, W/(V s))\n" ...
"Kp_dc = 112.6; Ki_dc = 4043;\n" ...
"errDc = VdcRef - Vdc;\n" ...
"dcInt = dcInt + Ki_dc*errDc*Ts;\n" ...
"dP = Kp_dc*errDc + dcInt;\n\n" ...
"pc = p - pbar - dP;   %% active power the APF must supply\n" ...
"qc = q;               %% APF supplies ALL reactive power (unity PF at source)\n\n" ...
"denom = vAlpha^2 + vBeta^2 + 1e-6;\n" ...
"icAlpha = (vAlpha*pc - vBeta*qc)/denom;   %% inverse of q = va*ib - vb*ia\n" ...
"icBeta  = (vBeta*pc + vAlpha*qc)/denom;\n\n" ...
"icRefA = icAlpha;\n" ...
"icRefB = -0.5*icAlpha + (sqrt(3)/2)*icBeta;\n" ...
"icRefC = -0.5*icAlpha - (sqrt(3)/2)*icBeta;\n" ...
"end\n"]);
end
